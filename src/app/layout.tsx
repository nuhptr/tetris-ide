import { Suspense } from "react"
import type { Metadata } from "next"
import { Inter, IBM_Plex_Mono } from "next/font/google"
import { ClerkProvider, SignInButton, SignUpButton, Show, UserButton } from "@clerk/nextjs"
import { dark } from "@clerk/themes"

import { cn } from "@/lib/utils"
import { ThemeProvider } from "@/components/theme-provider"

import "./globals.css"

const inter = Inter({
   variable: "--font-inter",
   subsets: ["latin"],
})

const plexMono = IBM_Plex_Mono({
   variable: "--font-plex-mono",
   subsets: ["latin"],
   // need weight this font
   weight: ["400", "500", "600", "700"],
})

export const metadata: Metadata = {
   title: "Tetris",
   description: "Generated by create next app",
}

export default function RootLayout({ children }: LayoutProps<"/">) {
   return (
      // Wrap entire html with clerk provider
      <ClerkProvider appearance={{ theme: dark }}>
         <html
            lang="en"
            className={cn("antialiased", inter.variable, plexMono.variable)}
            // suppress hydrated warning using this code
            suppressHydrationWarning
         >
            <body className="min-h-full">
               {/* Adding theme provider to add light or dark mode */}
               <ThemeProvider
                  attribute={"class"}
                  defaultTheme="dark"
                  enableSystem
                  disableTransitionOnChange
               >
                  <header>
                     <Suspense>
                        <Show when={"signed-out"}>
                           <SignInButton />
                           <SignUpButton>
                              <button className="bg-rose-500 text-white p-2 rounded">
                                 Sign Up
                              </button>
                           </SignUpButton>
                        </Show>
                        <Show when={"signed-in"}>
                           <UserButton />
                        </Show>
                     </Suspense>
                  </header>
                  {children}
               </ThemeProvider>
            </body>
         </html>
      </ClerkProvider>
   )
}
